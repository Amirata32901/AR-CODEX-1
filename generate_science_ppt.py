def rtl(p):
    p.alignment = PP_ALIGN.RIGHT
    p._p.get_or_add_pPr().append(parse_xml('<a:rtl %s val="1"/>' % nsdecls('a')))

def text(slide, x, y, w, h, value, size, color, bold=False, align=PP_ALIGN.RIGHT):
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame
    tf.clear()
    tf.word_wrap = True
    tf.margin_left = Inches(.08); tf.margin_right = Inches(.08)
    tf.margin_top = Inches(.03); tf.margin_bottom = Inches(.03)
    p = tf.paragraphs[0]
    rtl(p)
    p.alignment = align
    run = p.add_run()
    run.text = value
    run.font.name = "Vazirmatn"
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    return box

def panel(slide, x, y, w, h, color):
    s = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    s.fill.solid(); s.fill.fore_color.rgb = color
    s.line.fill.background()
    return s

